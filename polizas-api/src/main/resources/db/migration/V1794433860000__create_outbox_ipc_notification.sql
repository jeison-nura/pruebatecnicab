-- Outbox: the state change and the event are persisted in the same transaction.
-- The worker delivers to the CORE with retries + idempotency; PENDING/DELIVERED/FAILED tracking.
-- Sequential id: internal infrastructure table, ordering helps the worker (SKIP LOCKED);
-- policy_id is UUID because it references the domain aggregate.
CREATE TABLE policy.outbox_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type     VARCHAR(30)  NOT NULL,
    policy_id      UUID,
    payload        CLOB,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'DELIVERED', 'FAILED')),
    attempts       INT          NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(64) UNIQUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at   TIMESTAMP
);

-- IPC (CPI): percentage with application date; audits which CPI each renewal used.
CREATE TABLE policy.ipc (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_date DATE         NOT NULL UNIQUE,
    percentage      NUMERIC(6,4) NOT NULL
);

-- Notifications (schema notifications): email/SMS tracking.
-- The link to the policy is by id/correlation_id in the payload, never by a cross-schema FK.
CREATE TABLE notifications.notification (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel        VARCHAR(10)  NOT NULL CHECK (channel IN ('EMAIL', 'SMS')),
    recipient      VARCHAR(255) NOT NULL,
    policy_id      UUID,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    attempts       INT          NOT NULL DEFAULT 0,
    correlation_id VARCHAR(64),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at        TIMESTAMP
);
